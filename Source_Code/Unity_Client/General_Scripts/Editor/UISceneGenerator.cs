        [InitializeOnLoadMethod]
        private static void OnEditorLoad()
        {
            EditorApplication.delayCall += () =>
            {
                if (!EditorPrefs.GetBool(PREFS_KEY_AUTO_GENERATED, false))
                {
                    Debug.Log("[UISceneGenerator] First load detected - generating all PREP_VR UI scenes...");
                    GenerateAllUIScenes();
                    EditorPrefs.SetBool(PREFS_KEY_AUTO_GENERATED, true);
                }
            };
        }

        [MenuItem("PREP_VR/Generate All UI Scenes", priority = 10)]
        public static void GenerateAllUIScenes()
        {
            try
            {
                EnsureDirectoryExists();
                TMP_FontAsset font = AssetDatabase.LoadAssetAtPath<TMP_FontAsset>(FONT_PATH);

                CreateWelcomeScene(font);
                CreateHomeScreenScene(font);
                CreateInterviewTypeScene(font);
                CreateResumeUploadScene(font);
                CreateInterviewOverScene(font);

                UpdateBuildSettings();

                AssetDatabase.SaveAssets();
                AssetDatabase.Refresh();

                Debug.Log("<color=#10B981><b>[UISceneGenerator] SUCCESS:</b> All UI scenes created and added to Build Settings!</color>");
            }
            catch (Exception ex)
            {
                Debug.LogError($"[UISceneGenerator] Error generating UI scenes: {ex.Message}\n{ex.StackTrace}");
            }
        }

        [MenuItem("PREP_VR/Update Build Settings Only", priority = 20)]
        public static void UpdateBuildSettings()
        {
            string[] scenePaths = new string[]
            {
                "Assets/Scenes/UI/Welcome.unity",
                "Assets/Scenes/UI/HomeScreen.unity",
                "Assets/Scenes/UI/InterviewType.unity",
                "Assets/Scenes/UI/ResumeUpload.unity",
                "Assets/Scenes/InterviewRoom.unity",
                "Assets/Scenes/UI/InterviewOver.unity"
            };

            List<EditorBuildSettingsScene> buildScenes = new List<EditorBuildSettingsScene>();

            foreach (string path in scenePaths)
            {
                if (File.Exists(path))
                {
                    buildScenes.Add(new EditorBuildSettingsScene(path, true));
                    Debug.Log($"[UISceneGenerator] Build Settings: Registered scene -> {path}");
                }
                else
                {
                    Debug.LogWarning($"[UISceneGenerator] Scene path not found on disk: {path}");
                }
            }

            EditorBuildSettings.scenes = buildScenes.ToArray();
            Debug.Log($"[UISceneGenerator] Build Settings updated with {buildScenes.Count} scenes.");
        }

        private static void EnsureDirectoryExists()
        {
            if (!AssetDatabase.IsValidFolder("Assets/Scenes/UI"))
            {
                if (!AssetDatabase.IsValidFolder("Assets/Scenes"))
                {
                    AssetDatabase.CreateFolder("Assets", "Scenes");
                }
                AssetDatabase.CreateFolder("Assets/Scenes", "UI");
                Debug.Log("[UISceneGenerator] Created directory: Assets/Scenes/UI");
            }
        }

